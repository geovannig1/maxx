'use client'

import { useState } from 'react'
import Link from 'next/link'
import { toast } from 'sonner'
import type { CopyStudioData } from '@/lib/creative/copy-studio'
import type { GeneratedCopyVariant, RejectedCopyVariant, CopyGrounding } from '@/lib/creative/copy-generator'
import type { CopyScore } from '@/lib/creative/copy-scorer'
import { BriefForm, INITIAL_BRIEF, briefPayload, type BriefState } from './BriefForm'
import { VariantCard } from './VariantCard'
import { requestGenerate, requestSave, requestScoreText, variantClipboardText } from './copy-studio-client'

// The Copy studio: brief -> generated variants with deterministic scores -> copy, regenerate one angle,
// or save to the copy bank. Scoring pasted copy, the bank and the account's existing ads work with AI
// off; only generation needs a provider, and with AI off the button is disabled with the reason.

export const AI_OFF_NOTICE = 'AI is off. Connect a provider in Settings to generate copy. Scoring, the copy bank and the review of your existing ads still work.'

export interface CopyStudioProps {
  aiState: 'on' | 'off' | 'misconfigured'
  demo: boolean
  data: CopyStudioData
}

function copyToClipboard(text: string) {
  void navigator.clipboard.writeText(text).then(() => toast.success('Copied'), () => toast.error('The clipboard is not available'))
}

const comparableText = (v: GeneratedCopyVariant) => [v.primary_text, v.headline, v.description].join(' \n ')

export function CopyStudio({ aiState, demo, data }: CopyStudioProps) {
  const [brief, setBrief] = useState<BriefState>(INITIAL_BRIEF)
  const [busy, setBusy] = useState(false)
  const [status, setStatus] = useState('')
  const [variants, setVariants] = useState<GeneratedCopyVariant[]>([])
  const [rejected, setRejected] = useState<RejectedCopyVariant[]>([])
  const [grounding, setGrounding] = useState<CopyGrounding | null>(null)
  const [saved, setSaved] = useState<Set<number>>(new Set())
  const [pasted, setPasted] = useState('')
  const [pastedScore, setPastedScore] = useState<CopyScore | null>(null)

  const aiOff = aiState !== 'on'
  const disabledReason = aiOff ? AI_OFF_NOTICE : null

  async function generate() {
    setBusy(true)
    setStatus('Writing variants…')
    const outcome = await requestGenerate(briefPayload(brief))
    setBusy(false)
    if (!outcome.ok) { setStatus(outcome.message); return }
    setVariants(outcome.value.variants)
    setRejected(outcome.value.rejected)
    setGrounding(outcome.value.grounding)
    setSaved(new Set())
    setStatus(`${outcome.value.variants.length} variant${outcome.value.variants.length === 1 ? '' : 's'} ready.`)
  }

  async function regenerate(index: number) {
    const current = variants[index]
    setBusy(true)
    setStatus(`Rewriting the ${current.angle} angle…`)
    const outcome = await requestGenerate({ ...briefPayload(brief), variants: 1, angle: current.angle, avoid: [comparableText(current)] })
    setBusy(false)
    if (!outcome.ok) { setStatus(outcome.message); return }
    const next = outcome.value.variants[0]
    if (!next) { setStatus('No usable rewrite came back; the original is kept.'); setRejected(outcome.value.rejected); return }
    setVariants(variants.map((v, i) => (i === index ? next : v)))
    setSaved(new Set([...saved].filter((i) => i !== index)))
    setStatus('Angle rewritten.')
  }

  async function save(index: number) {
    setBusy(true)
    const outcome = await requestSave(variants[index], brief.goal, brief.temperature)
    setBusy(false)
    if (!outcome.ok) { setStatus(outcome.message); toast.error(outcome.message); return }
    setSaved(new Set([...saved, index]))
    setStatus('Saved to the copy bank.')
    toast.success('Saved to the copy bank')
  }

  async function scorePasted() {
    if (!pasted.trim()) return
    setStatus('Scoring…')
    const outcome = await requestScoreText(pasted, brief.goal)
    if (!outcome.ok) { setStatus(outcome.message); return }
    setPastedScore(outcome.value.score)
    setStatus(`Scored ${outcome.value.score.score}/100.`)
  }

  return (
    <div className="space-y-5">
      {aiOff && (
        <div className="owner-notice" role="note" data-ai-state={aiState}>
          <span className="font-semibold" style={{ color: 'var(--text-primary)' }}>{aiState === 'off' ? 'AI is off.' : 'AI is misconfigured.'}</span>{' '}
          Connect a provider in <Link href="/settings" className="underline">Settings</Link> to generate copy. Scoring, the copy bank and the review of your existing ads still work.
        </div>
      )}
      {demo && (
        <div className="owner-notice" role="note">
          Sample data: the copy bank below holds hand-written example variants from the demo dataset. They were not generated by AI, and saving is off in the demo.
        </div>
      )}

      <section aria-labelledby="copy-brief-heading" className="space-y-2">
        <h2 id="copy-brief-heading" className="section-label">Write new variants</h2>
        <BriefForm brief={brief} onChange={setBrief} onSubmit={generate} disabled={aiOff || brief.product.trim().length < 2} busy={busy} disabledReason={disabledReason} />
      </section>

      <p role="status" aria-live="polite" className="text-[12.5px]" style={{ color: 'var(--text-secondary)', minHeight: 18 }}>{status}</p>

      {variants.length > 0 && (
        <section aria-labelledby="copy-results-heading" className="space-y-3">
          <h2 id="copy-results-heading" className="section-label">Variants</h2>
          {grounding && (
            <p className="text-[12.5px]" style={{ color: 'var(--text-tertiary)' }}>
              Grounded in {grounding.verified_facts} verified fact{grounding.verified_facts === 1 ? '' : 's'}, {grounding.proven_copy} ranked hook{grounding.proven_copy === 1 ? '' : 's'} from your account and {grounding.hook_patterns} cited hook patterns.
              {grounding.social_proof_allowed ? '' : ' Social proof is off until the business profile holds a verified review or client fact.'}
            </p>
          )}
          <div className="grid grid-cols-1 lg:grid-cols-2 gap-3">
            {variants.map((v, i) => (
              <VariantCard key={`${i}-${v.hook}`} title={`Variant ${i + 1}`} variant={v} score={v.score} rationale={v.rationale}
                badge={v.status === 'ready' ? 'Ready' : v.status === 'review' ? 'Review' : 'Blocked'} busy={busy} saved={saved.has(i)}
                onCopy={() => copyToClipboard(variantClipboardText(v))} onRegenerate={aiOff ? undefined : () => void regenerate(i)} onSave={() => void save(i)} />
            ))}
          </div>
          {rejected.length > 0 && (
            <details className="text-[12.5px]" style={{ color: 'var(--text-secondary)' }}>
              <summary>{rejected.length} variant{rejected.length === 1 ? ' was' : 's were'} dropped</summary>
              <ul className="mt-1 space-y-1">{rejected.map((r, i) => <li key={i}>{r.hook ? `"${r.hook}": ` : ''}{r.detail}</li>)}</ul>
            </details>
          )}
        </section>
      )}

      <section aria-labelledby="copy-score-heading" className="space-y-2">
        <h2 id="copy-score-heading" className="section-label">Score your own copy</h2>
        <div className="card-base p-4 space-y-2">
          <label htmlFor="copy-paste" className="block text-[12.5px] font-medium">Primary text (the first line is read as the hook)</label>
          <textarea id="copy-paste" rows={4} maxLength={3000} value={pasted} onChange={(e) => setPasted(e.target.value)}
            style={{ width: '100%', border: '1px solid var(--border)', borderRadius: 6, padding: '8px 10px', fontSize: 13, background: 'var(--bg-surface)', color: 'var(--text-primary)' }} />
          <button type="button" className="owner-button" onClick={() => void scorePasted()} disabled={!pasted.trim()}
            style={{ border: '1px solid var(--border)', borderRadius: 6, fontSize: 13 }}>Score copy</button>
        </div>
        {pastedScore && <VariantCard title="Your copy" variant={{ primary_text: pasted }} score={pastedScore} onCopy={() => copyToClipboard(pasted)} />}
      </section>

      {data.status === 'account_unavailable' ? (
        <p className="owner-notice" role="note">The copy bank and your existing ads are unavailable because the active ad account could not be resolved ({data.code}).</p>
      ) : (
        <>
          <section aria-labelledby="copy-bank-heading" className="space-y-3">
            <h2 id="copy-bank-heading" className="section-label">Copy bank</h2>
            {data.bankReadHealth === 'unavailable' && <p className="text-[12.5px]" role="alert" style={{ color: 'var(--warning)' }}>The copy bank could not be read; this is not an empty bank.</p>}
            {data.bankReadHealth === 'healthy' && data.bank.length === 0 && <p className="text-[12.5px]" style={{ color: 'var(--text-tertiary)' }}>Nothing saved yet. Saved variants appear here, re-scored against your current verified facts.</p>}
            <div className="grid grid-cols-1 lg:grid-cols-2 gap-3">
              {data.bank.map((v) => (
                <VariantCard key={v.key} title={v.headline ?? v.hook ?? 'Saved variant'} variant={v} score={v.score}
                  badge={[v.sample ? 'Sample example (demo data, not AI)' : 'Saved', v.temperature, v.goal].filter(Boolean).join(' · ')}
                  onCopy={() => copyToClipboard(variantClipboardText(v))} />
              ))}
            </div>
          </section>

          <section aria-labelledby="copy-existing-heading" className="space-y-3">
            <h2 id="copy-existing-heading" className="section-label">Your existing ads, scored</h2>
            <p className="text-[12.5px]" style={{ color: 'var(--text-tertiary)' }}>The same rules applied to the copy your ads ran with. A score is about the words, not results: delivery and outcomes live on the Creative and Ads reports.</p>
            {data.adsReadHealth === 'unavailable' && <p className="text-[12.5px]" role="alert" style={{ color: 'var(--warning)' }}>The copy of your ads could not be read; this is not an empty account.</p>}
            {data.adsReadHealth === 'healthy' && data.existingAds.length === 0 && <p className="text-[12.5px]" style={{ color: 'var(--text-tertiary)' }}>No synced ad copy yet.</p>}
            <div className="grid grid-cols-1 lg:grid-cols-2 gap-3">
              {data.existingAds.map((ad) => (
                <VariantCard key={ad.creative_id} title={ad.name ?? `Creative ${ad.creative_id}`} variant={ad} score={ad.score}
                  onCopy={() => copyToClipboard(variantClipboardText(ad))} />
              ))}
            </div>
          </section>
        </>
      )}
    </div>
  )
}
