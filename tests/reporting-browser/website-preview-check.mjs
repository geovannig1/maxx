// Ordinary browser through the read-only fictional-data gateway, without request interception.
import assert from 'node:assert/strict'
import { mkdir, readFile } from 'node:fs/promises'
import { chromium, expect as browserExpect } from '@playwright/test'
const expect = browserExpect.configure({ timeout: 20000 })
const browser = await chromium.launch({ headless: true })
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, acceptDownloads: true })
const errors = []
page.on('pageerror', error => errors.push(error.message))
try {
  await page.goto('http://127.0.0.1:3149/preview?scenario=website', { waitUntil: 'domcontentloaded' })
  const opening = page.getByRole('region', { name: 'What deserves a closer look', exact: true })
  const mix = opening.locator('[data-review-id^="journey.mix:"]')
  await expect(mix).toContainText('74% to 36%')
  await expect(opening.locator('[data-review-id="journey.ga4.event_telemetry"]')).toContainText('appointment_confirmed')
  await expect(opening.locator('[data-review-id="journey.measurement.booking_lag"]')).toContainText('p90 39 days')
  await mkdir('test-results/reporting-preview', { recursive: true })
  await mix.scrollIntoViewIfNeeded()
  await page.screenshot({ path: 'test-results/reporting-preview/website-overview.png' })
  await mix.getByRole('link').click()
  await expect(page.getByRole('combobox', { name: 'Landing page filter', exact: true })).toHaveValue('/mix')
  const pages = page.getByRole('table', { name: 'Landing pages by device and channel' })
  const events = page.getByRole('table', { name: 'Observed website events' })
  await expect(pages.locator('tbody tr')).toHaveCount(2)
  await expect(pages).toContainText('Previous: 900')
  const clear = page.getByRole('button', { name: 'Clear website filters', exact: true })
  await clear.click()
  await expect(pages.locator('tbody tr')).toHaveCount(13)
  await expect(events.locator('tbody tr')).toHaveCount(3)
  const previousOnly = pages.locator('tbody tr').filter({ hasText: '/previous-only' })
  await expect(previousOnly).toContainText('Unavailable')
  await expect(previousOnly).toContainText('Previous: 25')
  // Navigate between actual existing fragment destinations while this same report stays loaded.
  const target = pages.locator('tbody tr').filter({ hasText: '/book' }).filter({ hasText: 'mobile' })
  const targetId = await target.getAttribute('id'), previousId = await previousOnly.getAttribute('id')
  const reportUrl = page.url().split('#')[0]
  await page.goto(`${reportUrl}#${targetId}`)
  await expect.poll(async () => { const b = await target.boundingBox(); return b && b.y >= 0 && b.y < 500 }).toBe(true)
  await page.goto(`${reportUrl}#${previousId}`)
  await expect.poll(async () => { const b = await previousOnly.boundingBox(); return b && b.y >= 0 && b.y < 500 }).toBe(true)
  await page.goBack()
  await expect.poll(async () => { const b = await target.boundingBox(); return b && b.y >= 0 && b.y < 500 }).toBe(true)
  await page.goForward()
  await expect.poll(async () => { const b = await previousOnly.boundingBox(); return b && b.y >= 0 && b.y < 500 }).toBe(true)
  const search = page.getByRole('searchbox', { name: 'Search website rows', exact: true })
  await search.fill('/book')
  await expect(pages.locator('tbody tr')).toHaveCount(2)
  await page.reload({ waitUntil: 'domcontentloaded' })
  await expect(search).toHaveValue('/book')
  await expect(pages.locator('tbody tr')).toHaveCount(2)
  const pending = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Export full website CSV', exact: true }).click()
  const download = await pending, csv = await readFile(await download.path(), 'utf8')
  for (const value of ['/gallery-8', '/previous-only', 'generate_lead', 'P90 paid-touch to booking lag']) assert.ok(csv.includes(value), value)
  await search.fill('not-a-supplied-cohort')
  await expect(pages.locator('tbody tr')).toHaveCount(0)
  await expect(events.locator('tbody tr')).toHaveCount(0)
  await expect(page.getByText('No landing-page rows match these filters.', { exact: true })).toBeVisible()
  await clear.click()
  await expect(pages.locator('tbody tr')).toHaveCount(13)
  for (const width of [1440, 390, 320]) {
    await page.setViewportSize({ width, height: 1000 })
    if (width < 1024) await expect(page.locator('#primary-nav')).toBeHidden()
    await pages.scrollIntoViewIfNeeded()
    await page.screenshot({ path: `test-results/reporting-preview/website-detail-${width}.png`, animations: 'disabled' })
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1), false, `body overflow at ${width}`)
  }
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.emulateMedia({ media: 'print' })
  await page.pdf({ path: 'test-results/reporting-preview/website-detail.pdf', format: 'A4', printBackground: true })
  await page.emulateMedia({ media: 'screen' })
  // A complete owner drill from a smaller named-event change, with its exact dimensions.
  await page.goto('http://127.0.0.1:3149/dashboard?from=2026-09-02&to=2026-09-04')
  await opening.locator('[data-review-id="journey.ga4.event_telemetry"]').getByRole('link').click()
  await expect(page.getByRole('combobox', { name: 'Event filter', exact: true })).toHaveValue('appointment_confirmed')
  await expect(events.locator('tbody tr')).toHaveCount(1)
  await expect(events).toContainText('Previous: 9')
  await expect.poll(async () => { const b = await events.locator('tbody tr').boundingBox(); return b && b.y >= 0 && b.y < 500 }).toBe(true)
  await page.goBack()
  await expect(opening.locator('[data-review-id="journey.ga4.event_telemetry"]')).toContainText('appointment_confirmed')
  assert.deepEqual(errors, [])
  console.log(JSON.stringify({ result: 'pass', pageRows: 13, eventRows: 3, mixReversal: true, exactDrillsAndHistory: true,
    fullExportDespiteSearch: true, observedLag: true, widths: [1440, 390, 320], errors }))
} finally { await browser.close() }
