// Ordinary loopback browser; fictional source data and no request interception.
import assert from 'node:assert/strict'
import { mkdir, readFile } from 'node:fs/promises'
import { chromium, expect as playwrightExpect } from '@playwright/test'
const expect = playwrightExpect.configure({ timeout: 20000 })
const browser = await chromium.launch({ headless: true })
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, acceptDownloads: true })
const errors = []
page.on('pageerror', error => errors.push(error.message))
try {
  await page.goto('http://127.0.0.1:3149/preview?scenario=audience', { waitUntil: 'domcontentloaded' })
  const overview = page.getByRole('region', { name: 'What deserves a closer look', exact: true })
  const concern = overview.locator('[data-review-id="audience_readiness:set-7"]')
  await expect(concern).toContainText('failed-exclusion')
  await expect(concern).toContainText('433')
  await concern.getByRole('link', { name: 'Inspect the affected audience roles and native statuses', exact: true }).click()
  await expect(page).toHaveURL(/report=audience.*#audience-adset-set-7/)
  const sets = () => page.locator('[id^="audience-adset-"]')
  await expect(sets()).toHaveCount(10)
  const seventh = page.locator('#audience-adset-set-7')
  const exclusion = seventh.locator('[data-audience-member="excluded:failed-exclusion"]')
  await expect(exclusion).toContainText('Operation status433')
  await expect(exclusion).toContainText('Delivery status200')
  await expect(exclusion).toContainText('Could not create lookalike')
  await expect.poll(async () => { const box = await seventh.boundingBox(); return !!box && box.y >= 0 && box.y < 500 }).toBe(true)
  await expect(seventh).toContainText('seed-b')
  await expect(seventh).toContainText('Selected-period performance')
  const search = page.getByRole('searchbox', { name: 'Search ad sets and audiences', exact: true })
  await search.fill('failed-exclusion')
  await expect(sets()).toHaveCount(2)
  await page.reload({ waitUntil: 'domcontentloaded' })
  await expect(search).toHaveValue('failed-exclusion')
  await expect(sets()).toHaveCount(2)
  const pendingDownload = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Export CSV', exact: true }).click()
  const download = await pendingDownload, csv = await readFile(await download.path(), 'utf8')
  assert.ok(csv.includes('set-10')) // full supplied export despite search
  assert.ok(csv.includes('failed-exclusion'))
  assert.ok(csv.includes('meta_configuration'))
  assert.ok(csv.includes('configuration_observation'))
  assert.ok(csv.includes('seed-a; seed-b'))
  assert.ok(csv.includes('not exact members'))
  assert.ok(!csv.includes('unused-failed'))
  await search.fill('impossible-audience-identity')
  await expect(sets()).toHaveCount(0)
  await expect(page.getByText('No ad sets match this search.', { exact: false })).toBeVisible()
  await page.getByRole('button', { name: 'Clear audience search', exact: true }).click()
  await expect(sets()).toHaveCount(10)
  await mkdir('test-results/reporting-preview', { recursive: true })
  for (const width of [1440, 390, 320]) {
    await page.setViewportSize({ width, height: 1000 })
    await page.screenshot({ path: `test-results/reporting-preview/audience-detail-${width}.png`, fullPage: true })
    await seventh.evaluate(element => element.scrollIntoView({ block: 'start' }))
    await page.screenshot({ path: `test-results/reporting-preview/audience-focus-${width}.png` })
    const overflow = await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth + 1)
    assert.equal(overflow, false, `page overflow at ${width}`)
    await expect(sets()).toHaveCount(10)
  }
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.emulateMedia({ media: 'print' })
  await page.pdf({ path: 'test-results/reporting-preview/audience-detail.pdf', format: 'A4', printBackground: true })
  await page.emulateMedia({ media: 'screen' })
  await page.goBack({ waitUntil: 'domcontentloaded' })
  await expect(concern).toBeVisible()
  assert.deepEqual(errors, [])
  console.log(JSON.stringify({ result: 'pass', suppliedAdSets: 10, searchedAdSets: 2, fullExportIncludesTenth: true, rolesAndNativeStatuses: true, sizes: [1440, 390, 320], errors }))
} finally { await browser.close() }
