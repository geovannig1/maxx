import React from 'react'
import { renderToStaticMarkup } from 'react-dom/server'
import { afterEach, describe, expect, it, vi } from 'vitest'

vi.mock('sonner', () => ({ toast: { success: vi.fn(), error: vi.fn() } }))

import { CopyStudio, AI_OFF_NOTICE } from '@/components/creative/copy-studio/CopyStudio'
import { VariantCard } from '@/components/creative/copy-studio/VariantCard'
import { requestSave, requestScoreText, variantClipboardText } from '@/components/creative/copy-studio/copy-studio-client'
import { scoreCopyVariant } from '@/lib/creative/copy-scorer'
import type { CopyStudioData } from '@/lib/creative/copy-studio'

// The suite has no DOM: markup is pinned by server-rendering each state, behaviour through the pure
// request helpers with a stubbed fetch.

const FACTS = { statements: ['north-facing daylight windows'], unverified: [] }
const CLEAN = { hook: 'Shooting products this week?', primary_text: 'Shooting products this week? Use our north-facing daylight windows. Book an hour.', headline: 'Daylight by the hour', description: 'Book online', cta: 'BOOK_NOW', angle: 'specific_benefit' }
const BLOCKED = { ...CLEAN, headline: 'The best studio in town' }
const score = (v: typeof CLEAN) => scoreCopyVariant(v, { facts: FACTS, goal: 'bookings' })

const DATA: CopyStudioData = {
  status: 'ok', bankReadHealth: 'healthy', adsReadHealth: 'healthy',
  bank: [{ key: 'k1', created_at: '2026-11-01T00:00:00Z', goal: 'bookings', temperature: 'cold', sample: true, ...CLEAN, score: score(CLEAN) }],
  existingAds: [{ creative_id: 'c1', name: 'Golden hour set', hook: CLEAN.hook, primary_text: CLEAN.primary_text, headline: 'Golden hour, any hour', description: null, cta: 'BOOK_NOW', score: score(CLEAN) }],
}

const render = (props: Partial<React.ComponentProps<typeof CopyStudio>> = {}) =>
  renderToStaticMarkup(<CopyStudio aiState="on" demo={false} data={DATA} {...props} />)

describe('Copy studio page', () => {
  it('shows the AI-off state with a disabled generate button, and keeps scoring available', () => {
    const html = render({ aiState: 'off' })
    expect(html).toContain('AI is off.')
    expect(html).toContain('href="/settings"')
    expect(html).toMatch(/<button type="submit"[^>]*disabled=""[^>]*>Generate variants<\/button>/)
    expect(html).toContain(AI_OFF_NOTICE)
    expect(html).toContain('Score your own copy')
    expect(html).toContain('Your existing ads, scored')
  })

  it('enables generation when AI is on (once a product is typed) and shows no AI-off notice', () => {
    const html = render()
    expect(html).not.toContain('AI is off.')
    expect(html).not.toContain(AI_OFF_NOTICE)
  })

  it('labels the demo bank as hand-written samples, not AI output', () => {
    const html = render({ aiState: 'off', demo: true })
    expect(html).toContain('Sample example (demo data, not AI)')
    expect(html).toContain('were not generated by AI')
    expect(html).toContain('Golden hour, any hour')
  })

  it('says unreadable data is unavailable, not empty', () => {
    const html = render({ data: { ...DATA, bank: [], existingAds: [], bankReadHealth: 'unavailable', adsReadHealth: 'unavailable' } })
    expect(html).toContain('this is not an empty bank')
    expect(html).toContain('this is not an empty account')
    expect(html).not.toContain('Nothing saved yet')
  })

  it('labels every form field', () => {
    const html = render()
    for (const id of ['copy-goal', 'copy-temperature', 'copy-product', 'copy-offer', 'copy-audience', 'copy-tone', 'copy-variants', 'copy-constraints', 'copy-paste']) {
      expect(html, id).toContain(`for="${id}"`)
      expect(html, id).toContain(`id="${id}"`)
    }
    expect(html).toContain('aria-live="polite"')
  })
})

describe('VariantCard', () => {
  it('renders the score as text, the findings with fixes, and disables saving a blocked variant', () => {
    const s = score(BLOCKED)
    const html = renderToStaticMarkup(<VariantCard title="Variant 1" variant={BLOCKED} score={s} onSave={() => undefined} onCopy={() => undefined} onRegenerate={() => undefined} />)
    expect(html).toContain(`${s.score}/100 · Blocked`)
    expect(html).toContain('data-rule="unverified_claim"')
    expect(html).toContain(s.findings[0].fix)
    expect(html).toMatch(/<button[^>]*disabled=""[^>]*>Fix blockers to save<\/button>/)
    expect(html).toContain('Regenerate this angle')
  })
  it('lets a clean variant be saved', () => {
    const html = renderToStaticMarkup(<VariantCard title="Variant 2" variant={CLEAN} score={score(CLEAN)} onSave={() => undefined} />)
    expect(html).toMatch(/<button[^>]*>Save to bank<\/button>/)
    expect(html).not.toMatch(/disabled=""[^>]*>Save to bank/)
    expect(html).toContain('No findings')
  })
})

describe('request helpers', () => {
  afterEach(() => vi.unstubAllGlobals())

  it('returns the server error message and code on a refused save', async () => {
    const fetchMock = vi.fn(async () => new Response(JSON.stringify({ error: 'This copy has a blocker.', code: 'COPY_NOT_PUBLISHABLE' }), { status: 422 }))
    vi.stubGlobal('fetch', fetchMock)
    const outcome = await requestSave({ ...CLEAN, angle: 'specific_benefit' }, 'bookings', 'cold')
    expect(outcome).toEqual({ ok: false, status: 422, code: 'COPY_NOT_PUBLISHABLE', message: 'This copy has a blocker.' })
    const sent = JSON.parse((fetchMock.mock.calls[0] as unknown as [string, RequestInit])[1].body as string)
    expect(sent).toEqual({ variant: { hook: CLEAN.hook, primary_text: CLEAN.primary_text, headline: CLEAN.headline, description: CLEAN.description, cta: 'BOOK_NOW', angle: 'specific_benefit' }, goal: 'bookings', temperature: 'cold' })
  })
  it('reports a network failure without throwing', async () => {
    vi.stubGlobal('fetch', vi.fn(async () => { throw new TypeError('offline') }))
    expect(await requestScoreText('hello there')).toMatchObject({ ok: false, code: 'NETWORK' })
  })
  it('formats a variant for the clipboard', () => {
    expect(variantClipboardText(CLEAN)).toBe(`Primary text:\n${CLEAN.primary_text}\n\nHeadline: Daylight by the hour\n\nDescription: Book online\n\nButton: Book now`)
  })
})
