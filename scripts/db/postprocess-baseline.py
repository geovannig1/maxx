#!/usr/bin/env python3
"""Turn a `pg_dump --schema-only --schema=public --no-owner` of a Supabase Postgres 17 database into a
migration that rebuilds the same schema on a fresh Supabase project. Used by squash-baseline.sh.

Each transformation exists because the raw dump is not a faithful migration on its own:
  * psql meta-commands (\\restrict) and PG17 session settings are not migration SQL;
  * `CREATE SCHEMA public` already exists on every Supabase project;
  * `FOR ROLE supabase_admin` default privileges belong to the platform, not to this app;
  * pg_dump writes each object's ACL as GRANTs relative to an EMPTY start, so objects must be created
    with no default grants and the final defaults restored at the end, or grants silently widen;
  * the browser roles (anon, authenticated) must hold no object privileges at all, and PUBLIC's
    built-in EXECUTE on functions can only be removed explicitly (a per-schema default cannot).
Usage: postprocess-baseline.py <raw-dump.sql> <out.sql>
"""
import re
import sys

HEADER = """-- Maxx baseline schema.
--
-- Generated by scripts/db/squash-baseline.sh from the migration chain on Supabase Postgres 17: the
-- public schema's tables, views, functions, triggers, row-level security, policies and grants.
-- Regenerate it with that script; do not hand-edit large sections. Requires Postgres 17.

CREATE SCHEMA IF NOT EXISTS extensions;
CREATE EXTENSION IF NOT EXISTS "uuid-ossp" WITH SCHEMA extensions;
CREATE EXTENSION IF NOT EXISTS pgcrypto WITH SCHEMA extensions;

-- While the schema is built, new objects get NO grants beyond their owner. pg_dump records each
-- object's exact ACL as GRANT statements relative to that empty starting point, so any default here
-- would silently widen them (append-only ledgers granted only SELECT to service_role would become
-- writable). The final default privileges are restored at the end of this file.
ALTER DEFAULT PRIVILEGES FOR ROLE postgres IN SCHEMA public REVOKE ALL ON TABLES FROM PUBLIC, anon, authenticated, service_role;
ALTER DEFAULT PRIVILEGES FOR ROLE postgres IN SCHEMA public REVOKE ALL ON SEQUENCES FROM PUBLIC, anon, authenticated, service_role;
ALTER DEFAULT PRIVILEGES FOR ROLE postgres IN SCHEMA public REVOKE ALL ON FUNCTIONS FROM PUBLIC, anon, authenticated, service_role;
"""

FOOTER = """
-- Functions: Postgres grants EXECUTE to PUBLIC by default, and a per-schema default privilege cannot
-- remove that built-in grant (only a database-wide one can). Revoke it from every existing function
-- and from future ones, so the browser roles can execute nothing. Trigger functions keep working:
-- EXECUTE is checked when a trigger is created, not when it fires.
REVOKE EXECUTE ON ALL FUNCTIONS IN SCHEMA public FROM PUBLIC, anon, authenticated;
ALTER DEFAULT PRIVILEGES FOR ROLE postgres REVOKE EXECUTE ON FUNCTIONS FROM PUBLIC;
"""

DROP_LINE = re.compile(
    r"^(\\(un)?restrict .*"
    r"|SET transaction_timeout = .*"
    r"|CREATE SCHEMA public;"
    r"|COMMENT ON SCHEMA public IS .*"
    r"|ALTER DEFAULT PRIVILEGES FOR ROLE supabase_admin .*"
    r"|GRANT [^\n]+ ON (FUNCTION|SEQUENCE|TABLE) [^\n]+ TO (anon|authenticated);"
    r"|GRANT [^\n]+ ON FUNCTION [^\n]+ TO PUBLIC;)$"
)
FINAL_DEFAULT = re.compile(r"^ALTER DEFAULT PRIVILEGES FOR ROLE postgres IN SCHEMA public GRANT .*$")


def main(src: str, dst: str) -> None:
    kept, finals, dropped = [], [], 0
    for line in open(src, encoding="utf-8").read().split("\n"):
        if DROP_LINE.match(line):
            dropped += 1
            continue
        if FINAL_DEFAULT.match(line):
            finals.append(line)
            continue
        kept.append(line)
    body = "\n".join(kept).strip("\n")
    if re.search(r"^GRANT (?!USAGE ON SCHEMA public)[^\n]* TO [^\n]*\b(anon|authenticated)\b", body, re.M):
        sys.exit("refusing: a grant to a browser role survived post-processing")
    out = (
        HEADER + "\n" + body + "\n\n"
        + "-- Final default privileges for objects created later (the browser roles still get nothing).\n"
        + "\n".join(finals) + "\n" + FOOTER
    )
    open(dst, "w", encoding="utf-8").write(out)
    print(f"dropped {dropped} lines; final default privileges: {len(finals)}", file=sys.stderr)


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    main(sys.argv[1], sys.argv[2])
