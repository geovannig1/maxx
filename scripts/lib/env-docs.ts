import { ENV_GROUPS, ENV_VARS } from '../../src/config/env'
import type { EnvVarSpec, Requirement } from '../../src/config/env-spec'

// Pure renderers for the generated configuration reference and the env template. Both come from the
// schema in src/config/env.ts; tests/env-docs-fresh.test.ts fails when the committed files differ.

export const CONFIGURATION_DOC = 'docs/configuration.md'
export const ENV_TEMPLATE = 'config/env.example.template'

function requirementText(rule: Requirement): string {
  switch (rule.kind) {
    case 'required': return 'yes'
    case 'production': return 'in production'
    case 'dashboard': return 'before the dashboard shows data'
    case 'when': return rule.text
    case 'optional': return 'no'
  }
}

const cell = (value: string) => value.replace(/\|/g, '\\|').replace(/\n/g, ' ')

function row(spec: EnvVarSpec): string {
  const flags = [spec.secret ? 'secret' : '', spec.public ? 'public (browser)' : '', spec.scope === 'build' ? 'build time' : '',
    spec.scope === 'script' ? 'scripts only' : '', spec.deprecatedBy ? `deprecated: use \`${spec.deprecatedBy}\`` : '']
    .filter(Boolean).join(', ')
  const setup = spec.setup === 'generate' ? ' Generated by `npm run setup`.' : spec.setup === 'derived' ? ' Recorded by `npm run setup`.' : ''
  return `| \`${spec.name}\` | ${cell(requirementText(spec.required))} | ${cell(flags || '-')} | ${spec.default !== undefined ? `\`${cell(spec.default)}\`` : '-'} | ${cell(spec.format.hint)} | ${cell(spec.description + setup)} |`
}

export function renderConfigurationDoc(): string {
  const lines = [
    '# Configuration reference',
    '',
    '<!-- Generated from src/config/env.ts by `npm run env:docs`. Do not edit by hand. -->',
    '',
    'Every environment variable Maxx reads, generated from the one schema in',
    '[`src/config/env.ts`](../src/config/env.ts). The server validates it at startup and logs each',
    'problem by variable name, never by value; `npm run doctor` and the in-app setup checklist',
    '(`/setup`) run the same checks. `npm run setup` writes `.env.local` (mode 600) for you.',
    '',
    `${ENV_VARS.length} variables, ${ENV_VARS.filter((s) => s.secret).length} secret, ${ENV_VARS.filter((s) => s.public).length} public.`,
    '',
    '- **Secret** values are never printed, logged, returned by an API or shown in the app.',
    '- **Public** (`NEXT_PUBLIC_*`) values are inlined into the browser bundle at build time: change',
    '  them, then rebuild. No secret is ever public (enforced by `tests/env-schema-population.test.ts`).',
    '- Secrets stay in environment variables: Vercel cannot write them at runtime. Non-secret settings',
    '  that the app stores (outcome sources on or off) are changed in the app.',
    '',
  ]
  for (const group of ENV_GROUPS) {
    const specs = ENV_VARS.filter((s) => s.group === group.id)
    if (specs.length === 0) continue
    lines.push(`## ${group.title}`, '', group.intro, '',
      '| Variable | Required | Kind | Default | Format | Meaning |', '|---|---|---|---|---|---|',
      ...specs.map(row), '')
  }
  lines.push('## Development and test variables', '',
    'Read only by tests and tooling, never by the app: `SB_*` (local Supabase for integration tests),',
    '`E2E_*` (Playwright against a running deployment), `MAXX_EVAL_*`, `PROMPTFOO_*`, `OTEL_*`,',
    '`MAXX_TEST_*`, `MAXX_REPORTING_SCENARIO`, `MAXX_RECORDED_PACKETS`, `REPORTING_CREATIVE_UI_BROWSER`,',
    '`DIGEST_PREVIEW`, `MAXX_EXPLAIN_WITHHOLD`.', '')
  return lines.join('\n')
}

/** Template for the env file: every non-platform variable, required ones first, no values. */
export function renderEnvTemplate(): string {
  const lines = [
    '# Maxx environment template, generated from src/config/env.ts by `npm run env:docs`.',
    '# `npm run setup` writes .env.local for you; this file documents every variable.',
    '# Never commit real values. Reference: docs/configuration.md',
    '',
  ]
  for (const group of ENV_GROUPS) {
    const specs = ENV_VARS.filter((s) => s.group === group.id && s.scope !== 'platform')
    if (specs.length === 0) continue
    lines.push(`# ── ${group.title} ${'─'.repeat(Math.max(4, 90 - group.title.length))}`)
    for (const spec of specs) {
      const required = requirementText(spec.required)
      lines.push(`# ${spec.description}`, `#   required: ${required}${spec.secret ? '; secret' : ''}${spec.default !== undefined ? `; default ${spec.default}` : ''}`)
      lines.push(`${spec.required.kind === 'optional' && spec.setup !== 'generate' ? '# ' : ''}${spec.name}=${spec.secret ? '' : spec.example ?? ''}`)
    }
    lines.push('')
  }
  return lines.join('\n')
}
